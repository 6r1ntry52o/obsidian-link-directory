export type I18nKey = keyof typeof en;

export function t(key: I18nKey): string {
	let lang = "en";
	try {
		lang = window.localStorage.getItem("language") ?? "en";
	} catch {
		/* storage unavailable */
	}
	return (lang.startsWith("ja") ? ja : en)[key];
}
